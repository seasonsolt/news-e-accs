import assert from "node:assert/strict";
import { test } from "node:test";
import { htmlLanguage, requestLocale, publicPath, localePath, languageSwitchPath, hasChineseRoute, languagePreference, prefersChinese } from "../app/lib/locale.ts";
import { translate } from "../app/lib/translate.ts";

test("URL language is stable across browser languages and preference cookies, including data requests", () => {
  for (const path of ["/", "/all", "/weekly.data", "/_.data", "/items/123"]) {
    for (const language of ["en", "zh-CN", "zh-HK,en;q=0.8"]) {
      for (const cookie of ["", "eacc_language=zh", "eacc_language=en; admin_session=secret"]) {
        assert.equal(requestLocale(new Request(`https://e-acc.ai${path}`, { headers: { cookie, "accept-language": language } })), "en");
      }
    }
  }
  for (const path of ["/zh", "/zh/", "/zh/all", "/zh/weekly.data", "/zh/_.data", "/zh.data"]) {
    assert.equal(requestLocale(new Request(`https://e-acc.ai${path}`, { headers: { cookie: "eacc_language=en", "accept-language": "en" } })), "zh");
  }
  assert.equal(requestLocale(new Request("https://e-acc.ai/admin/login")), "zh");
  assert.equal(htmlLanguage("en"), "en");
  assert.equal(htmlLanguage("zh"), "zh-CN");
});
test("edition navigation preserves filters and keeps APIs, admin and assets unprefixed", () => {
  assert.equal(localePath("/all?q=robot&category=model#results", "zh"), "/zh/all?q=robot&category=model#results");
  assert.equal(localePath("/zh/all?q=robot", "en"), "/all?q=robot");
  assert.equal(localePath("/", "zh"), "/zh");
  for (const path of ["/admin", "/api/site/items", "/feed/picks.xml", "/og/items/123.png", "/assets/file.js", "/items/123/markdown", "//external.example/all"]) {
    assert.equal(localePath(path, "zh"), path);
  }
  for (const slug of ["what-is-eacc", "eacc-vs-dacc", "eacc-glossary"]) {
    assert.equal(hasChineseRoute(`/${slug}`), true);
    assert.equal(localePath(`/${slug}`, "zh"), `/zh/${slug}`);
    assert.equal(localePath(`/zh/${slug}`, "en"), `/${slug}`);
  }
  assert.equal(publicPath("/zh/weekly/2026-W39.data"), "/weekly/2026-W39");
  assert.equal(publicPath("/zh/_.data"), "/");
  assert.equal(languageSwitchPath("/zh/all", "?q=robot&page=2&cursor=old&_routes=root&lang=zh", "#results", "en"), "/all?q=robot&page=2#results");
});
test("explicit UI copy, placeholders and numeric units translate without changing unknown news", () => {
  assert.equal(translate("en", "精选"), "Picks");
  assert.equal(translate("en", "历史事件"), "Historical event");
  assert.equal(translate("en", "AI 根据报道生成 · {0}更新", translate("en", "4 天前")), "Generated by AI from reports · Updated 4 days ago");
  assert.equal(translate("en", "上一期 · 第 39 周"), "Previous issue · Week 39");
  assert.equal(translate("zh", "{0} 个来源", 3), "3 个来源");
  assert.equal(translate("en", "{0} 个来源", 3), "3 sources");
  assert.equal(translate("en", "3 分钟前"), "3 minutes ago");
  assert.equal(translate("en", "3.6 万"), "36K");
  assert.equal(translate("en", "2026 年 9 月 1 日 · 星期二"), "2026-09-01 · Tuesday");
  assert.equal(translate("en", "2026年9月1日 周二"), "2026-09-01 Tue");
  assert.equal(translate("en", "这是数据库中已发布的中文新闻标题"), "这是数据库中已发布的中文新闻标题");
});


test("native English site copy keeps explicit Chinese counterparts and news remains untouched", () => {
  assert.equal(translate("zh", "Today’s AI news: editorial picks and emerging stories"), "今日 AI 新闻：精选与新兴事件");
  assert.equal(translate("zh", "Built on open-source software"), "基于开源软件构建");
  assert.equal(translate("zh", "Native English news headline"), "Native English news headline");
});
test("the Chinese-edition hint reads only an explicit choice and the browser's first language", () => {
  assert.equal(languagePreference(""), null);
  assert.equal(languagePreference("eacc_language=zh"), "zh");
  assert.equal(languagePreference("theme=dark; eacc_language=en"), "en");
  assert.equal(languagePreference("not_eacc_language=zh"), null);
  assert.equal(languagePreference("eacc_language=fr"), null);
  for (const languages of [["zh-CN"], ["zh"], ["zh-Hant-TW", "en"], ["ZH-hk"]]) assert.equal(prefersChinese(languages), true);
  for (const languages of [[], ["en-US", "zh-CN"], ["zhx"], ["ja"]]) assert.equal(prefersChinese(languages), false);
});
test("time machine labels read in English, Chinese spans included", () => {
  const cases: Array<[string, string]> = [
    ["100亿年前", "10 billion years ago"], ["1000万年前", "10 million years ago"], ["1万年前", "10,000 years ago"],
    ["1个月前", "1 month ago"], ["1年后", "in 1 year"], ["约5000年前", "about 5,000 years ago"],
    ["距今 1.2 亿年", "120 million years ago"], ["距今 300 年", "300 years ago"], ["5 年后", "in 5 years"],
    ["3 个月后出现", "Available in 3 months"], ["公元前500年", "500 BCE"], ["1769年", "1769"], ["2024年3月", "2024-03"],
    ["数据始于{0}", "data begins {0}"],
  ];
  for (const [zh, en] of cases) assert.equal(translate("en", zh), en, zh);
  assert.equal(translate("zh", "100亿年前"), "100亿年前");
});
